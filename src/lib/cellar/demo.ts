const today = new Date().toISOString().slice(0, 10);

function midpoint(from: string) {
  const a = new Date(`${from}T12:00:00`).getTime();
  return new Date((a + Date.now()) / 2).toISOString().slice(0, 10);
}

export function demoCellar(): CellarData {
  const data: CellarData = {
    items: [],
    events: [],
    valuations: [],
    asOf: Date.now(),
    racks: [
      { id: "rack-A", name: "Keller · Regal links", compartments: 2, rows: 2 },
      { id: "rack-B", name: "Keller · Regal rechts", compartments: 2, rows: 2 },
      { id: "rack-C", name: "Weinkühlschrank", compartments: 2, rows: 2 },
    ],
  };
  ROWS.forEach((r, i) => {
    const id = `demo-${i}`;
    const [producer, name, vintage, color, grape, region, classification, qty, price, bought] = r;
    data.items.push({
      id,
      producer,
      name,
      vintage,
      color,
      grape,
      region,
      classification,
      quantity: qty,
      purchasePrice: price,
      purchasedOn: bought,
      drinkFrom: r[10],
      drinkUntil: r[11],
      rackId: `rack-${r[12]}`,
      compartment: r[13],
      row: r[14],
    });
    data.events.push({
      id: `${id}-p`,
      itemId: id,
      kind: "purchase",
      quantity: qty,
      unitPrice: price,
      date: bought,
    });
    data.valuations.push(
      {
        id: `${id}-v1`,
        itemId: id,
        value: Math.round(((price + r[15]) / 2) * 100) / 100,
        source: "manual",
        date: midpoint(bought),
      },
      { id: `${id}-v2`, itemId: id, value: r[15], source: "manual", date: today },
    );
  });
  return data;
}
